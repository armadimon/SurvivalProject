using System.Collections;
using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.InputSystem;

public class PlayerInteraction : MonoBehaviour
{
    public float checkRate = 0.05f;
    private float lastCheckTime;
    public float maxCheckDistance;
    public LayerMask layerMask;     // ??????????μ떜媛?걫??곸쁼筌??????μ떜媛?걫???

    // ?????獄쏅챶留???????ル뒌?????????????????????ル뒌???????嚥〓끃異??????????????Β?ル윲??
    public GameObject curInteractGameObject;
    private IInteractable curInteractable; // ?????ル뒌?????????????????Β?ル윲???IInteractable ??饔낅떽???嶺뚮슢梨뜹ㅇ??????곌떽釉붾???

    public TextMeshProUGUI promptText; // ???????????????? ????????UI
    private Camera cam;

    // Start is called before the first frame update
    void Start()
    {
        cam = Camera.main;
    }

    // Update is called once per frame
    void Update()
    {
        if (Time.time - lastCheckTime > checkRate)
        {
            lastCheckTime = Time.time;

            // ????椰?壤???????袁ⓦ걤???ш낄猷???????????μ떜媛?걫??곸쁼筌????????????????욱뒅?????????????썹땟洹욌뙀?
            Ray ray = cam.ScreenPointToRay(new Vector3(Screen.width / 2, Screen.height / 2, 0));
            RaycastHit hit;

            if (Physics.Raycast(ray, out hit, maxCheckDistance, layerMask))
            {
                // ???????????????????????Β?ル윲????????ル뒌???????μ떜媛?걫?????汝뷴젆?琉????????????댁댉??????諛몃마???
                if (hit.collider.gameObject != curInteractGameObject)
                {
                    curInteractGameObject = hit.collider.gameObject;
                    curInteractable = hit.collider.GetComponent<IInteractable>();

                    SetPromptText();
                }
            }
            else
            {
                curInteractGameObject = null;
                curInteractable = null;
                promptText.gameObject.SetActive(false);
            }
        }
    }

    private void SetPromptText()
    {
        promptText.gameObject.SetActive(true);
        promptText.text = curInteractable.GetInteractPrompt();
    }

    public void OnInteractInput(InputAction.CallbackContext context)
    {
        if (context.phase == InputActionPhase.Started && curInteractable != null)
        {
            curInteractable.OnInteract();
            curInteractGameObject = null;
            curInteractable = null;
            promptText.gameObject.SetActive(false);
        }
    }
}
